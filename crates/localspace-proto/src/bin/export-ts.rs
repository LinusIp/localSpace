//! `cargo run -p localspace-proto --bin export-ts`: write the TypeScript
//! client's types from `proto` into `web/src/api/generated/` (architecture
//! v2 §5: generated, never written by hand). The test in
//! `tests/typescript.rs` does the same and checks the result; this binary is
//! for the machine where a freshly built test executable is refused by the
//! operating system's application control (docs/DECISIONS.md, 2026-09-10).

#![deny(unsafe_code)]

use localspace_proto as proto;
use std::path::{Path, PathBuf};
use ts_rs::{Config, TS};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let dir = match std::env::args().nth(1) {
        Some(given) => PathBuf::from(given),
        None => Path::new(env!("CARGO_MANIFEST_DIR")).join("../../web/src/api/generated"),
    };
    std::fs::create_dir_all(&dir)?;
    // Ids and counts are `u64` in Rust and plain numbers in JSON: `bigint`
    // would be wrong on the receiving side of `JSON.parse`.
    let cfg = Config::new().with_out_dir(&dir).with_large_int("number");
    proto::Envelope::export_all(&cfg)?;

    let mut names: Vec<String> = std::fs::read_dir(&dir)?
        .filter_map(|entry| {
            let name = entry.ok()?.file_name().into_string().ok()?;
            let stem = name.strip_suffix(".ts")?;
            (stem != "index").then(|| stem.to_string())
        })
        .collect();
    names.sort();
    let mut index = String::from(
        "// Generated by `cargo test -p localspace-proto` from crates/localspace-proto. Do not edit.\n",
    );
    for name in &names {
        index.push_str(&format!("export type {{ {name} }} from \"./{name}\";\n"));
    }
    std::fs::write(dir.join("index.ts"), index)?;
    // Silent on success, like any build step; a failure surfaces as the
    // error itself through `main`'s result.
    Ok(())
}
